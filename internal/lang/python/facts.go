package python

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"path"
	"regexp"
	"strings"

	"github.com/Git-Hospital/githealthcheck/internal/facts"
)

// Prepare sets the facts that follow from a file's path and header, without python3: its package (a
// directory), whether it is a test, and whether it is generated.
func Prepare(f *facts.File, src []byte) {
	f.Package = path.Dir(f.Path)
	f.Test = isTest(f.Path)
	f.Generated = generated(src)
}

// isTest reports a test file as pytest and unittest find them: test_*.py, *_test.py, a Django tests.py,
// conftest.py (fixtures), and everything under a tests or test directory, where the helpers of the
// tests live too.
func isTest(rel string) bool {
	base := path.Base(rel)
	stem := strings.TrimSuffix(strings.TrimSuffix(base, ".py"), ".pyi")
	if strings.HasPrefix(stem, "test_") || strings.HasSuffix(stem, "_test") || stem == "tests" || stem == "conftest" {
		return true
	}
	for part := range strings.SplitSeq(path.Dir(rel), "/") {
		if part == "tests" || part == "test" {
			return true
		}
	}
	return false
}

// generatedMark matches the headers code generators write: the Go convention, which other generators
// use too, @generated, and protoc's.
var generatedMark = regexp.MustCompile(`(?i)(code generated .* do not edit|@generated\b|generated by the protocol buffer compiler)`)

// generated reports whether one of the comment lines before the first line of code marks the file as
// generated.
func generated(src []byte) bool {
	sc := bufio.NewScanner(bytes.NewReader(src))
	for n := 0; sc.Scan() && n < 50; n++ {
		line := strings.TrimSpace(sc.Text())
		switch {
		case line == "":
		case strings.HasPrefix(line, "#"):
			if generatedMark.MatchString(line) {
				return true
			}
		default:
			return false
		}
	}
	return false
}

// response is what the helper sends for one file. Keys are short: the token arrays of a large file
// are most of it.
type response struct {
	Error   string `json:"error"`
	Partial bool   `json:"partial"`
	Parsed  bool   `json:"parsed"` // ast read the file: without it there are no functions to measure
	Funcs   []struct {
		Name       string   `json:"n"`
		Line       int      `json:"l"`
		EndLine    int      `json:"e"`
		Lines      int      `json:"c"`
		Statements int      `json:"s"`
		Cognitive  int      `json:"cog"`
		Cyclomatic int      `json:"cyc"`
		Nesting    int      `json:"nest"`
		Method     bool     `json:"m"`
		Exported   bool     `json:"x"`
		Span       [2]int32 `json:"sp"`
	} `json:"f"`
	Imports []struct {
		Path     string `json:"p"`
		Line     int    `json:"l"`
		Optional bool   `json:"o"`
	} `json:"i"`
	Smells []struct {
		Kind    facts.SmellKind `json:"k"`
		Line    int             `json:"l"`
		EndLine int             `json:"e"`
		Func    string          `json:"f"`
	} `json:"sm"`
	Refs  []string `json:"r"`
	Kinds []uint8  `json:"tk"`
	Names []uint32 `json:"tn"`
	Lines []int32  `json:"tl"`
}

// MaxSmells is the number of smells of each kind kept per file, as for Go.
const MaxSmells = 1000

// fill sets f's facts from the helper's response. A file that did not parse comes back with what the
// tokenizer got and Partial set. restart says the helper ran out of memory and is better replaced.
func fill(f *facts.File, resp []byte, tokens bool) (restart bool, err error) {
	var r response
	if err := json.Unmarshal(resp, &r); err != nil {
		return true, err
	}
	restart = r.Error == "MemoryError"
	if r.Error != "" || !r.Parsed {
		// Nothing was measured: the file counts in no measurement, as one that was not read.
		return restart, fmt.Errorf("python3 helper: not parsed (%s)", r.Error)
	}
	f.Partial = r.Partial
	for _, fn := range r.Funcs {
		f.Funcs = append(f.Funcs, facts.Function{Name: fn.Name, Line: fn.Line, EndLine: fn.EndLine, Lines: fn.Lines,
			Statements: fn.Statements, Cognitive: fn.Cognitive, Cyclomatic: fn.Cyclomatic, Nesting: fn.Nesting,
			Method: fn.Method, Exported: fn.Exported, Span: fn.Span})
	}
	f.Functions = len(f.Funcs)
	for _, im := range r.Imports {
		f.Imports = append(f.Imports, facts.Import{Path: im.Path, Line: im.Line, Optional: im.Optional})
	}
	count := map[facts.SmellKind]int{}
	for _, s := range r.Smells {
		if count[s.Kind]++; count[s.Kind] > MaxSmells {
			if f.SmellsDropped == nil {
				f.SmellsDropped = map[facts.SmellKind]int{}
			}
			f.SmellsDropped[s.Kind]++
			continue
		}
		f.Smells = append(f.Smells, facts.Smell{Kind: s.Kind, Line: s.Line, EndLine: s.EndLine, Func: s.Func})
	}
	f.Refs = r.Refs
	if tokens && len(r.Kinds) == len(r.Names) && len(r.Kinds) == len(r.Lines) {
		f.Tokens = facts.Tokens{Kind: r.Kinds, Name: r.Names, Line: r.Lines}
		for i := range f.Funcs {
			if sp := f.Funcs[i].Span; sp[0] < 0 || sp[1] > int32(len(r.Kinds)) || sp[0] > sp[1] {
				f.Funcs[i].Span = [2]int32{}
			}
		}
	} else {
		for i := range f.Funcs {
			f.Funcs[i].Span = [2]int32{}
		}
	}
	return restart, nil
}

// wantTokens reports whether duplication is looked for in a file: the repository's own code, not
// tests, vendored or generated files.
func wantTokens(f *facts.File) bool {
	return !f.Test && !f.Generated && !f.Vendored
}
