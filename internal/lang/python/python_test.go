// needPython skips a test without a python3 of MinVersion or later, unless GHC_REQUIRE_PYTHON is set,
// as it is in CI, where a skip would hide a broken helper.
func needPython(t *testing.T) {
	t.Helper()
	p, err := Start(context.Background())
	if err == nil {
		p.Close()
		return
	}
	if os.Getenv("GHC_REQUIRE_PYTHON") != "" {
		t.Fatalf("python3: %v", err)
	}
	t.Skipf("python3: %v", err)
}

// run fills each source as a file of the given path and returns the files in order.
func run(t *testing.T, files map[string]string, order ...string) []facts.File {
	t.Helper()
	p, err := Start(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	for i, path := range order {
		p.Submit(i, facts.File{Path: path, Language: "python"}, []byte(files[path]))
	}
	out := make([]facts.File, len(order))
	for _, r := range p.Wait() {
		out[r.Index] = r.File
	}
	return out
}

func TestFunctions(t *testing.T) {
	needPython(t)
	src := `"""A module."""
import os


def plain(a, b):
    """Doc
    string."""
    if a:
        return b
    elif b:
        return a
    else:
        return None


class Box:
    def _get(self, items):
        for i in items:
            while i:
                try:
                    with open(i) as f:
                        if f:
                            i = f.read() if i else None
                except (OSError, ValueError):
                    pass
        return [x for x in items if x and x.ok or x.bad]

    class Inner:
        def __eq__(self, other):
            return True


if os.name == "nt":
    def windows():
        pass
`
	all := run(t, map[string]string{"pkg/m.py": src, "pkg/m.pyi": "def plain(a: int, b: int) -> int: ...\n"}, "pkg/m.py", "pkg/m.pyi")
	if stub := all[1]; stub.Analysed || len(stub.Funcs) != 0 {
		t.Errorf("type stub: %+v", stub)
	}
	f := all[0]
	if !f.Analysed || f.Partial || f.Package != "pkg" || f.Test {
		t.Fatalf("file: %+v", f)
	}
	type want struct {
		name                    string
		line, end, lines, stmts int
		cog, cyc, nest          int
		method, exported        bool
	}
	wants := []want{
		{"plain", 5, 13, 6, 1, 3, 3, 1, false, true},
		// Sonar: for 1, while 2, if 3 (try and with bodies do not nest), ternary 4, except 3, the
		// comprehension's and/or 2: 15. radon: 1 + for 1 + while 1 + except 1 + if 1 + ternary 1 +
		// comprehension 2 + or/and 2 = 10. Nesting (S134): for, while, try, with, if = 5.
		{"Box._get", 17, 26, 9, 2, 15, 10, 5, true, false},
		{"Box.Inner.__eq__", 29, 30, 1, 1, 0, 1, 0, true, true},
		{"windows", 34, 35, 1, 1, 0, 1, 0, false, true},
	}
	if len(f.Funcs) != len(wants) {
		t.Fatalf("functions: %+v", f.Funcs)
	}
	for i, w := range wants {
		g := f.Funcs[i]
		got := want{g.Name, g.Line, g.EndLine, g.Lines, g.Statements, g.Cognitive, g.Cyclomatic, g.Nesting, g.Method, g.Exported}
		if got != w {
			t.Errorf("function %d:\n got %+v\nwant %+v", i, got, w)
		}
	}
	if len(f.Imports) != 1 || f.Imports[0] != (facts.Import{Path: "os", Line: 2}) {
		t.Errorf("imports: %+v", f.Imports)
	}
}

// A function's span starts after its name, wherever the def is: after a block (where DEDENT tokens
// share the def's position), in a class, or async.
func TestSpans(t *testing.T) {
	needPython(t)
	src := `def a(x):
    if x:
        return 1


def b(y):
    return y


class C:
    async def c(self):
        return 2
`
	f := run(t, map[string]string{"m.py": src}, "m.py")[0]
	if len(f.Funcs) != 3 {
		t.Fatalf("functions: %+v", f.Funcs)
	}
	for _, fn := range f.Funcs {
		if sp := fn.Span; sp[1] <= sp[0] || f.Tokens.Kind[sp[0]] != 140+7 { // tokenize.LPAR
			t.Errorf("%s: span %v starts at kind %d", fn.Name, sp, f.Tokens.Kind[fn.Span[0]])
		}
	}
}

func TestPathFacts(t *testing.T) {
	for path, test := range map[string]bool{
		"a/test_x.py": true, "a/x_test.py": true, "app/tests.py": true, "conftest.py": true,
		"tests/helpers.py": true, "src/pkg/test/util.py": true,
		"testing/x.py": false, "a/contest.py": false, "a/latest.py": false, "x.py": false,
	} {
		if isTest(path) != test {
			t.Errorf("%s: test %v", path, !test)
		}
	}
	for src, gen := range map[string]bool{
		"# Generated by the protocol buffer compiler.  DO NOT EDIT!\n":           true,
		"#!/usr/bin/env python\n# Code generated by x. DO NOT EDIT.\nimport a\n": true,
		"# @generated by tool\n":                          true,
		"import a\n# Code generated by x. DO NOT EDIT.\n": false,
		"# hand written\n":                                false,
	} {
		if generated([]byte(src)) != gen {
			t.Errorf("%q: generated %v", src, !gen)
		}
	}
}

func TestSmells(t *testing.T) {
	needPython(t)
	src := `def todo():
    # TODO: write this
    pass


def later():
    raise NotImplementedError


class Base:
    def hook(self):
        raise NotImplementedError

    def unfinished(self):
        raise NotImplementedError("TODO")


def swallow():
    try:
        work()
    except Exception:
        pass
    try:
        work()
    except KeyError:
        pass
    try:
        work()
    except:
        pass  # deliberate: best effort


def stub():
    ...


# result = compute(x)
# if result:
#     save(result)

# This explains: the thing (2) below.
# Note: something
x = 1  # y = 2

# flags: --minimum-version=3.10
# Note: x = 1

# limit: int | None = None
`
	f := run(t, map[string]string{"m.py": src}, "m.py")[0]
	var got []string
	for _, s := range f.Smells {
		got = append(got, string(s.Kind)+":"+s.Func+":"+itoa(s.Line)+"-"+itoa(s.EndLine))
	}
	want := []string{
		"placeholder:todo:1-3",
		"placeholder:later:6-7",
		"placeholder:Base.unfinished:14-15",
		"except_ignored:swallow:21-22",
		"commented_code::37-39",
		"commented_code::48-48",
	}
	if strings.Join(got, " ") != strings.Join(want, " ") {
		t.Errorf("smells\n got %v\nwant %v", got, want)
	}
}

func itoa(n int) string { return strconv.Itoa(n) }

// Code that does not parse comes back partial and not analysed, so it counts in no measurement;
// crafted input does not stop the helper: deep nesting, null bytes, a bad encoding, an unterminated
// string.
func TestHostileInput(t *testing.T) {
	needPython(t)
	deep := strings.Repeat("(", 5000) + "1" + strings.Repeat(")", 5000) + "\n"
	nested := ""
	for i := range 300 {
		nested += strings.Repeat(" ", i) + "if x:\n"
	}
	nested += strings.Repeat(" ", 300) + "pass\n"
	files := map[string]string{
		"deep.py":   deep,
		"nested.py": "def f(x):\n" + indent(nested),
		"null.py":   "x = 1\x00\n",
		"enc.py":    "# -*- coding: no-such-codec -*-\nx = 1\n",
		"open.py":   "def f():\n    s = '''never closed\n",
		"ok.py":     "def g():\n    return 1\n",
	}
	order := []string{"deep.py", "nested.py", "null.py", "enc.py", "open.py", "ok.py"}
	got := run(t, files, order...)
	for i, f := range got[:5] {
		if f.Analysed || !f.Partial {
			t.Errorf("%s: %+v", order[i], f)
		}
	}
	if ok := got[5]; !ok.Analysed || ok.Partial || len(ok.Funcs) != 1 {
		t.Errorf("after hostile input: %+v", ok)
	}
}

func indent(s string) string {
	lines := strings.Split(strings.TrimSuffix(s, "\n"), "\n")
	for i := range lines {
		lines[i] = " " + lines[i]
	}
	return strings.Join(lines, "\n") + "\n"
}

// A python3 older than MinVersion is refused, with the reason tool_too_old.
func TestTooOld(t *testing.T) {
	old := "/usr/bin/python3"
	out, err := exec.Command(old, "-c", "import sys; print(sys.version_info[:2] < (3, 10))").Output()
	if err != nil || strings.TrimSpace(string(out)) != "True" {
		t.Skip("no python3 older than 3.10 at /usr/bin/python3")
	}
	defer func(p string) { Interpreter = p }(Interpreter)
	Interpreter = old
	if _, err := Start(context.Background()); Reason(err) != "tool_too_old" {
		t.Errorf("python 3.9: %v", err)
	}
}

// A helper that dies or hangs costs its file, not the scan: the file is partial and not analysed,
// and the next file is read by a new helper, however many files before it killed one.
func TestHelperDies(t *testing.T) {
	needPython(t)
	dir := t.TempDir()
	// The fake interpreter greets like the helper and answers each file, but dies on a file that
	// holds "die" and hangs on one that holds "hang".
	fake := filepath.Join(dir, "python3")
	script := `#!/bin/sh
echo 'githealthcheck-python 3.12.0'
while read -r header; do
	read -r body
	case "$body" in
	*die*) exit 1 ;;
	*hang*) exec sleep 60 ;;
	esac
	echo '{"partial":false,"parsed":true,"f":[{"n":"ok","l":1,"e":1,"c":1,"s":1}]}'
done
`
	if err := os.WriteFile(fake, []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	defer func(p string, d time.Duration) { Interpreter, fileTimeout = p, d }(Interpreter, fileTimeout)
	Interpreter, fileTimeout = fake, 2*time.Second
	p, err := Start(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	const bad = 16 // four for each of up to four helpers, past any bound on restarts
	p.Submit(0, facts.File{Path: "hang.py", Language: "python"}, []byte("hang\n"))
	for i := 1; i <= bad; i++ {
		p.Submit(i, facts.File{Path: "die.py", Language: "python"}, []byte("die\n"))
	}
	for i := bad + 1; i <= bad+8; i++ {
		p.Submit(i, facts.File{Path: "ok.py", Language: "python"}, []byte("ok\n"))
	}
	got := map[int]facts.File{}
	for _, r := range p.Wait() {
		got[r.Index] = r.File
	}
	for i := 0; i <= bad+8; i++ {
		f := got[i]
		if ok := i > bad; f.Analysed != ok || f.Partial == ok || ok && len(f.Funcs) != 1 {
			t.Errorf("file %d (%s): analysed %v partial %v functions %d", i, f.Path, f.Analysed, f.Partial, len(f.Funcs))
		}
	}
}

