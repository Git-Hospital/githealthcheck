func TestPackage(t *testing.T) {
	for rel, want := range map[string]string{
		"main.go":                     ".",
		"internal/x/x.go":             "internal/x",
		"internal/x/x_test.go":        "internal/x",
		"testdata/a.go":               "",
		"pkg/testdata/deep/a.go":      "",
		"_examples/a.go":              "",
		"pkg/_old/a.go":               "",
		".hidden/a.go":                "",
		"pkg/_skip.go":                "",
		"pkg/.skip.go":                "",
		"pkg/notestdata/a.go":         "pkg/notestdata",
		"pkg/under_score/a.go":        "pkg/under_score",
		"vendor/example.com/m/a.go":   "vendor/example.com/m",
		"pkg/testdata_helpers/a.go":   "pkg/testdata_helpers",
		"pkg/x.go/inner/not_a_dir.go": "pkg/x.go/inner",
	} {
		if got := Package(rel); got != want {
			t.Errorf("Package(%q) = %q, want %q", rel, got, want)
		}
	}
}

func TestFill(t *testing.T) {
	for _, c := range []struct {
		name, path, src string
		want            facts.File
	}{
		{"functions and methods", "a/a.go", "package a\n\ntype T struct{}\n\nfunc (T) M() {}\n\nfunc F() {}\n",
			facts.File{Package: "a", Functions: 2}},
		{"a declaration without a body is not counted", "a/asm.go", "package a\n\nfunc Add(x, y int) int\n",
			facts.File{Package: "a"}},
		{"func literals are not declarations", "a/lit.go", "package a\n\nvar f = func() {}\n",
			facts.File{Package: "a"}},
		{"test file", "a/a_test.go", "package a\n\nimport \"testing\"\n\nfunc TestX(t *testing.T) {}\n",
			facts.File{Test: true, Package: "a", Functions: 1}},
		{"generated", "a/gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage a\n\nfunc G() {}\n",
			facts.File{Generated: true, Package: "a", Functions: 1}},
		{"marker after the package clause does not count", "a/late.go", "package a\n// Code generated by x. DO NOT EDIT.\n",
			facts.File{Package: "a"}},
		{"a file that does not parse is counted as far as the parser got", "a/broken.go", "package a\n\nfunc A() {}\n\nfunc B( {\n",
			facts.File{Package: "a", Functions: 1, Partial: true}},
		{"not Go at all", "a/junk.go", "\x00\xff garbage",
			facts.File{Package: "a", Partial: true}},
		{"ignored by the go command", "testdata/t.go", "package t\n\nfunc F() {}\n",
			facts.File{Functions: 1}},
	} {
		t.Run(c.name, func(t *testing.T) {
			f := facts.File{Path: c.path}
			Support{}.Fill(&f, []byte(c.src))
			c.want.Path = c.path
			f.Funcs, f.Imports, f.Smells, f.Refs = nil, nil, nil, nil // checked by their own tests
			if !reflect.DeepEqual(f, c.want) {
				t.Errorf("got %+v, want %+v", f, c.want)
			}
		})
	}
}

func TestModulePath(t *testing.T) {
	for src, want := range map[string]string{
		"module example.com/m\n\ngo 1.22\n":                       "example.com/m",
		"// header\nmodule example.com/m // trailing\n":           "example.com/m",
		"module \"example.com/quoted\"\n":                         "example.com/quoted",
		"module `example.com/raw`\n":                              "example.com/raw",
		"module example.com/crlf\r\n":                             "example.com/crlf",
		"  module   example.com/spaces  \n":                       "example.com/spaces",
		"go 1.22\n":                                               "",
		"module (\n\texample.com/block\n)\n":                      "",
		"module \"unterminated\n":                                 "",
		"module a b\n":                                            "",
		"// module example.com/commented\n":                       "",
		"require example.com/x v1.0.0\nmodule example.com/late\n": "example.com/late",
	} {
		if got := ModulePath([]byte(src)); got != want {
			t.Errorf("ModulePath(%q) = %q, want %q", src, got, want)
		}
	}
}

