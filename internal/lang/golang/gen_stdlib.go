//go:build ignore

// gen_stdlib writes stdlib.go: the import paths of the standard library of the Go toolchain that runs
// it, so an import can be checked offline. They are the directories of GOROOT/src that hold Go files,
// for every platform and experiment (go list std leaves out syscall/js and the like). Run with
// go generate ./internal/lang/golang.
package main

import (
	"bytes"
	"fmt"
	"go/build"
	"go/format"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"runtime"
	"slices"
	"strings"
)

func main() {
	src := filepath.Join(build.Default.GOROOT, "src")
	var pkgs []string
	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		rel = filepath.ToSlash(rel)
		if d.IsDir() && rel != "." {
			// Not importable from outside the standard library, or not packages at all.
			for part := range strings.SplitSeq(rel, "/") {
				if part == "internal" || part == "testdata" || part == "vendor" || strings.HasPrefix(part, ".") || strings.HasPrefix(part, "_") {
					return fs.SkipDir
				}
			}
			if rel == "cmd" {
				return fs.SkipDir
			}
			return nil
		}
		if d.IsDir() {
			return nil
		}
		if strings.HasSuffix(p, ".go") && !strings.HasSuffix(p, "_test.go") {
			dir := filepath.ToSlash(filepath.Dir(rel))
			// builtin only documents the predeclared names: it cannot be imported.
			if dir != "." && dir != "builtin" && (len(pkgs) == 0 || pkgs[len(pkgs)-1] != dir) {
				pkgs = append(pkgs, dir)
			}
		}
		return nil
	})
	if err != nil {
		log.Fatal(err)
	}
	slices.Sort(pkgs)
	pkgs = slices.Compact(pkgs)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_stdlib.go from GOROOT/src of %s. DO NOT EDIT.\n\npackage golang\n\n", runtime.Version())
	fmt.Fprintf(&b, "// stdlibVersion is the Go release the list was made from.\nconst stdlibVersion = %q\n\n", runtime.Version())
	b.WriteString("// stdlib holds the import paths of the standard library. \"C\" is cgo's pseudo-package.\n")
	b.WriteString("var stdlib = map[string]bool{\n\t\"C\": true,\n")
	for _, p := range pkgs {
		fmt.Fprintf(&b, "\t%q: true,\n", p)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("stdlib.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
