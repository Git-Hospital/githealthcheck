//go:build ignore

// gen_stdlib writes stdlib.go: the import paths of the standard library of the Go toolchain that runs
// it (go list std), so an import can be checked offline. Run with go generate ./internal/lang/golang.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"runtime"
	"strings"
)

func main() {
	out, err := exec.Command("go", "list", "std").Output()
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_stdlib.go from go list std of %s. DO NOT EDIT.\n\npackage golang\n\n", runtime.Version())
	b.WriteString("// stdlib holds the import paths of the standard library. \"C\" is cgo's pseudo-package.\n")
	b.WriteString("var stdlib = map[string]bool{\n\t\"C\": true,\n")
	for _, p := range strings.Fields(string(out)) {
		if strings.HasPrefix(p, "vendor/") || strings.Contains(p, "/internal/") || strings.HasPrefix(p, "internal/") || strings.HasSuffix(p, "/internal") {
			continue // not importable from outside the standard library
		}
		fmt.Fprintf(&b, "\t%q: true,\n", p)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("stdlib.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
