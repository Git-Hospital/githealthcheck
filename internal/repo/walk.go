// Package repo walks a repository's work tree once and classifies every source file. It treats the
// tree as untrusted: symlinks are never followed, oversized files are never read, and nested
// repositories are left out because their history is not this repository's.
package repo

import (
	"bufio"
	"bytes"
	"context"
	"errors"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"syscall"

	"github.com/Git-Hospital/githealthcheck/internal/report"
)

// MaxSourceBytes is the largest source file that is read (architecture §2).
const MaxSourceBytes = 1 << 20

// File is one source file in a recognised language.
type File struct {
	Path      string // slash-separated, relative to the root
	Language  string
	Size      int64
	Lines     int
	Vendored  bool // under a vendored dependency directory
	Generated bool // marked as generated by its own header
}

// Tree is the result of a walk.
type Tree struct {
	Root    string
	Files   []File
	Skipped []report.Skip
}

// vendorDirs are directory names whose contents are third-party code.
var vendorDirs = map[string]bool{"vendor": true, "node_modules": true, "third_party": true, "bower_components": true}

// Walk reads the tree under root. Directories named .git are not entered; a directory that contains a
// .git entry of its own is a nested repository and is skipped.
func Walk(ctx context.Context, root string) (*Tree, error) {
	t := &Tree{Root: root}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if ctx.Err() != nil {
			return ctx.Err()
		}
		rel, _ := filepath.Rel(root, path)
		rel = filepath.ToSlash(rel)
		if err != nil {
			if path == root {
				return err
			}
			t.Skipped = append(t.Skipped, report.Skip{Path: rel, Reason: report.SkipUnreadable, Detail: cause(err)})
			if d != nil && d.IsDir() {
				return fs.SkipDir
			}
			return nil
		}
		// WalkDir reports symlinks without following them; d.Type() comes from lstat. Every symlink is
		// listed, since telling a link to a directory from a link to a file would mean following it.
		if d.Type()&fs.ModeSymlink != 0 {
			t.Skipped = append(t.Skipped, report.Skip{Path: rel, Reason: report.SkipSymlink})
			return nil
		}
		if d.IsDir() {
			if d.Name() == ".git" {
				return fs.SkipDir
			}
			if path != root {
				if _, err := os.Lstat(filepath.Join(path, ".git")); err == nil {
					t.Skipped = append(t.Skipped, report.Skip{Path: rel, Reason: report.SkipNestedRepo})
					return fs.SkipDir
				}
			}
			return nil
		}
		lang := language(rel)
		if lang == "" {
			return nil
		}
		if !d.Type().IsRegular() {
			t.Skipped = append(t.Skipped, report.Skip{Path: rel, Reason: report.SkipNotRegular})
			return nil
		}
		src, size, reason, err := readSource(path)
		if reason != "" {
			s := report.Skip{Path: rel, Reason: reason}
			if err != nil {
				s.Detail = cause(err)
			}
			t.Skipped = append(t.Skipped, s)
			return nil
		}
		t.Files = append(t.Files, File{
			Path:      rel,
			Language:  lang,
			Size:      size,
			Lines:     countLines(src),
			Vendored:  vendored(rel),
			Generated: generated(lang, src),
		})
		return nil
	})
	// On cancellation the files read so far are still returned, so a timed-out run can report what it
	// did measure.
	return t, err
}

// readSource reads a regular file without following a symlink swapped in after the walk saw it, without
// blocking on a FIFO swapped in, and without reading past MaxSourceBytes even if the file grows. The
// type and size come from the open descriptor, not from the earlier lstat.
func readSource(path string) (src []byte, size int64, reason report.SkipReason, err error) {
	f, err := os.OpenFile(path, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
	if err != nil {
		if errors.Is(err, syscall.ELOOP) {
			return nil, 0, report.SkipSymlink, nil
		}
		return nil, 0, report.SkipUnreadable, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return nil, 0, report.SkipUnreadable, err
	}
	if !info.Mode().IsRegular() {
		return nil, 0, report.SkipNotRegular, nil
	}
	if info.Size() > MaxSourceBytes {
		return nil, 0, report.SkipTooLarge, nil
	}
	src, err = io.ReadAll(io.LimitReader(f, MaxSourceBytes+1))
	if err != nil {
		return nil, 0, report.SkipUnreadable, err
	}
	if len(src) > MaxSourceBytes {
		return nil, 0, report.SkipTooLarge, nil
	}
	return src, int64(len(src)), "", nil
}

// cause describes an error without the path it carries: reports must not contain the user's absolute
// paths.
func cause(err error) string {
	switch {
	case errors.Is(err, fs.ErrPermission):
		return "permission denied"
	case errors.Is(err, fs.ErrNotExist):
		return "does not exist"
	}
	var pe *fs.PathError
	if errors.As(err, &pe) {
		return pe.Err.Error()
	}
	return "unreadable"
}

func countLines(src []byte) int {
	n := bytes.Count(src, []byte{'\n'})
	if len(src) > 0 && src[len(src)-1] != '\n' {
		n++
	}
	return n
}

func vendored(rel string) bool {
	for part := range strings.SplitSeq(rel, "/") {
		if vendorDirs[part] {
			return true
		}
	}
	return false
}

// goGenerated is the convention from https://go.dev/s/generatedcode.
var goGenerated = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)

// generated reports whether a file marks itself as generated. Only Go has a fixed convention; other
// languages are added with their language support.
func generated(lang string, src []byte) bool {
	if lang != "go" {
		return false
	}
	sc := bufio.NewScanner(bytes.NewReader(src))
	for sc.Scan() {
		line := sc.Text()
		if goGenerated.MatchString(line) {
			return true
		}
		if strings.HasPrefix(line, "package ") {
			return false
		}
	}
	return false
}
