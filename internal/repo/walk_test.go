func write(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestWalk(t *testing.T) {
	root := t.TempDir()
	outside := t.TempDir()
	write(t, outside, "secret.go", "package secret\n// outside the repository\n")

	write(t, root, "main.go", "package main\n\nfunc main() {}\n")
	write(t, root, "lib/no_newline.go", "package lib")
	write(t, root, "vendor/dep/dep.go", "package dep\n")
	write(t, root, "web/node_modules/x/index.js", "module.exports = 1\n")
	write(t, root, "gen.go", "// Code generated by stringer; DO NOT EDIT.\n\npackage main\n")
	write(t, root, "not_gen.go", "package main\n\n// Code generated by hand; DO NOT EDIT.\n")
	write(t, root, "tool.rs", "fn main() {}\n")
	write(t, root, "README.md", "# readme\n")
	write(t, root, ".git/objects/x.go", "package objects\n")
	write(t, root, "sub/.git/HEAD", "ref: refs/heads/main\n")
	write(t, root, "sub/inner.go", "package inner\n")
	write(t, root, "big.go", "package big\n"+strings.Repeat("// pad\n", MaxSourceBytes/7+1))
	if err := os.Symlink(filepath.Join(outside, "secret.go"), filepath.Join(root, "link.go")); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, filepath.Join(root, "linkdir")); err != nil {
		t.Fatal(err)
	}

	tree, err := Walk(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}

	files := map[string]File{}
	for _, f := range tree.Files {
		files[f.Path] = f
	}
	want := map[string]File{
		"main.go":                     {Language: "go", Lines: 3},
		"lib/no_newline.go":           {Language: "go", Lines: 1},
		"vendor/dep/dep.go":           {Language: "go", Lines: 1, Vendored: true},
		"web/node_modules/x/index.js": {Language: "javascript", Lines: 1, Vendored: true},
		"gen.go":                      {Language: "go", Lines: 3, Generated: true},
		"not_gen.go":                  {Language: "go", Lines: 3},
		"tool.rs":                     {Language: "rust", Lines: 1},
	}
	if len(files) != len(want) {
		t.Errorf("files = %v, want exactly %d", keys(files), len(want))
	}
	for p, w := range want {
		f, ok := files[p]
		if !ok {
			t.Errorf("%s missing", p)
			continue
		}
		if f.Language != w.Language || f.Lines != w.Lines || f.Vendored != w.Vendored || f.Generated != w.Generated {
			t.Errorf("%s = %+v, want %+v", p, f, w)
		}
	}

	skipped := map[string]report.SkipReason{}
	for _, s := range tree.Skipped {
		skipped[s.Path] = s.Reason
	}
	wantSkipped := map[string]report.SkipReason{
		"link.go": report.SkipSymlink,
		"linkdir": report.SkipSymlink,
		"sub":     report.SkipNestedRepo,
		"big.go":  report.SkipTooLarge,
	}
	for p, r := range wantSkipped {
		if skipped[p] != r {
			t.Errorf("skipped[%s] = %q, want %q", p, skipped[p], r)
		}
	}
	if len(skipped) != len(wantSkipped) {
		t.Errorf("skipped = %v, want exactly %v", skipped, wantSkipped)
	}
}

func keys(m map[string]File) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	return out
}

func TestWalkCancelled(t *testing.T) {
	root := t.TempDir()
	write(t, root, "a.go", "package a\n")
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := Walk(ctx, root); err == nil {
		t.Fatal("Walk ignored a cancelled context")
	}
}

func TestWalkSpecialAndUnreadable(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("root reads files whatever their mode")
	}
	root := t.TempDir()
	write(t, root, "ok.go", "package ok\n")
	write(t, root, "locked.go", "package locked\n")
	write(t, root, "lockeddir/x.go", "package x\n")
	if err := syscall.Mkfifo(filepath.Join(root, "pipe.go"), 0o644); err != nil {
		t.Fatal(err)
	}
	os.Chmod(filepath.Join(root, "locked.go"), 0)
	os.Chmod(filepath.Join(root, "lockeddir"), 0)
	t.Cleanup(func() { os.Chmod(filepath.Join(root, "lockeddir"), 0o755) })

	tree, err := Walk(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]report.Skip{}
	for _, s := range tree.Skipped {
		got[s.Path] = s
		if strings.Contains(s.Detail, root) {
			t.Errorf("skip detail %q contains the absolute path", s.Detail)
		}
	}
	if got["pipe.go"].Reason != report.SkipNotRegular {
		t.Errorf("pipe.go skipped as %q, want %q", got["pipe.go"].Reason, report.SkipNotRegular)
	}
	for _, p := range []string{"locked.go", "lockeddir"} {
		if got[p].Reason != report.SkipUnreadable || got[p].Detail != "permission denied" {
			t.Errorf("%s = %+v, want unreadable / permission denied", p, got[p])
		}
	}
	if len(tree.Files) != 1 || tree.Files[0].Path != "ok.go" {
		t.Errorf("files = %+v, want only ok.go", tree.Files)
	}
}

// readSource is what Walk calls after its lstat; these are the files an attacker could swap in between
// the two.
func TestReadSourceSwappedFiles(t *testing.T) {
	dir := t.TempDir()
	outside := t.TempDir()
	write(t, outside, "secret.go", "package secret\n")
	write(t, dir, "target.go", "package target\n")
	r, err := os.OpenRoot(dir)
	if err != nil {
		t.Fatal(err)
	}
	defer r.Close()

	// A file, or a directory on the way to it, swapped for a symlink that leaves the root.
	os.Symlink(filepath.Join(outside, "secret.go"), filepath.Join(dir, "link.go"))
	os.Symlink(outside, filepath.Join(dir, "d"))
	for _, rel := range []string{"link.go", "d/secret.go"} {
		src, _, reason, _ := readSource(r, rel)
		if reason != report.SkipUnreadable || src != nil {
			t.Errorf("%s: read %q with reason %q, want it refused", rel, src, reason)
		}
	}

	fifo := filepath.Join(dir, "fifo.go")
	if err := syscall.Mkfifo(fifo, 0o644); err != nil {
		t.Fatal(err)
	}
	done := make(chan report.SkipReason, 1)
	go func() { _, _, r, _ := readSource(r, "fifo.go"); done <- r }()
	select {
	case r := <-done:
		if r != report.SkipNotRegular {
			t.Errorf("fifo read with reason %q, want %q", r, report.SkipNotRegular)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("readSource blocked on a FIFO")
	}

	write(t, dir, "big.go", strings.Repeat("x", MaxSourceBytes+1))
	if _, _, reason, _ := readSource(r, "big.go"); reason != report.SkipTooLarge {
		t.Errorf("big file read with reason %q", reason)
	}
	if src, size, reason, err := readSource(r, "target.go"); reason != "" || err != nil || size != 15 || string(src) != "package target\n" {
		t.Errorf("regular file: %q %d %q %v", src, size, reason, err)
	}
}

// A file that was small at fstat and then grew is cut off, not read whole.
func TestReadCappedGrowth(t *testing.T) {
	_, _, reason, _ := readCapped(strings.NewReader(strings.Repeat("x", MaxSourceBytes+1)))
	if reason != report.SkipTooLarge {
		t.Errorf("reason %q, want %q", reason, report.SkipTooLarge)
	}
	src, size, reason, _ := readCapped(strings.NewReader(strings.Repeat("x", MaxSourceBytes)))
	if reason != "" || size != MaxSourceBytes || len(src) != MaxSourceBytes {
		t.Errorf("file at the limit: size %d reason %q", size, reason)
	}
}
