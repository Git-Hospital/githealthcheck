// Package facts is the model the analyzers read. Each file is read and parsed once, during the walk;
// analyzers never open files themselves.
package facts

// File is one source file in a recognised language, as it is in the work tree.
type File struct {
	Path      string // slash-separated, relative to the root
	Language  string
	Size      int64
	Lines     int
	Vendored  bool // under a vendored dependency directory
	Modified  bool // the work tree's content differs from the commit's blob
	Generated bool // marked as generated by its own header
	Test      bool // a test file by its language's convention
	// Package is the unit the file belongs to, a directory for Go. It is empty when the language's
	// own tooling ignores the file, as the go command ignores testdata and directories that start
	// with _ or .
	Package   string
	Functions int  // function and method declarations with a body
	Partial   bool // the source did not parse in full: the facts cover what the parser got
	// Funcs describes each of them, in source order, for the languages that measure functions.
	Funcs []Function
	// Imports are the packages the file imports, in source order.
	Imports []Import
	// Smells are the places in the file that match a pattern of D32, at most a thousand of each
	// kind; SmellsDropped counts the rest by kind.
	Smells        []Smell
	SmellsDropped map[SmellKind]int
	// Tokens is the token stream that duplication is found in: the repository's own code only, not
	// tests, vendored or generated files. The walk drops every file's stream once the repository has
	// more than MaxTokens, and sets TokensDropped.
	Tokens        Tokens
	TokensDropped bool
	// Refs holds every name the file uses that could refer to a function of its package: identifiers
	// other than the names of the declarations themselves, and the names that //export and
	// //go:linkname directives make reachable from outside. Sorted, without duplicates.
	Refs []string
}

// MaxTokens bounds the tokens kept for duplication, about two and a half million lines of Go; past
// it duplication is not looked for. The streams take 9 bytes a token, and finding clones in them up
// to about 40 more: a crafted repository of 14.5 million tokens peaked at 670 MB.
const MaxTokens = 20_000_000

// Tokens is a file's tokens after its imports, without comments, as parallel slices.
type Tokens struct {
	// Kind is the token with every identifier one kind and every literal another, so that renamed
	// copies compare equal.
	Kind []uint8
	// Name is a hash of an identifier's or literal's text, to check that a copy renames
	// consistently, with bit 30 set for the name of a function's own parameter, result or local,
	// which a copy may rename, bit 31 for any other name, which it must keep, and both for a
	// literal; 0 for other tokens.
	Name []uint32
	// Line is the token's line in the file.
	Line []int32
}

// Import is one imported package.
type Import struct {
	Path string
	Line int
}

// SmellKind is a pattern of D32 found in one place.
type SmellKind string

const (
	// EmptyErrorCheck is `if err != nil {}`: the error is checked and nothing is done.
	EmptyErrorCheck SmellKind = "empty_error_check"
	// ErrorDropped is `if err != nil { return nil }` in a function that returns an error: the error
	// is checked and replaced by success.
	ErrorDropped SmellKind = "error_dropped"
	// Placeholder is a body that only says it is not implemented.
	Placeholder SmellKind = "placeholder"
	// CommentedCode is a run of comment lines that parse as code.
	CommentedCode SmellKind = "commented_code"
)

// Smell is one place that matches a pattern.
type Smell struct {
	Kind          SmellKind
	Line, EndLine int
	Func          string // the enclosing function, when there is one
}

// Function is one function or method declaration with a body.
type Function struct {
	Name          string // "F", or "T.M" for a method
	Line, EndLine int    // of the declaration, 1-based
	// Lines counts the lines of the body that hold code, between the line of the opening brace and
	// the line of the closing one: blank lines and lines holding only comments do not count.
	Lines      int
	Statements int // statements directly in the body
	Cognitive  int // cognitive complexity (Campbell, SonarSource 2018)
	Cyclomatic int // McCabe, counted as gocyclo counts
	Nesting    int // deepest nesting of control-flow statements; an else if does not nest
	Method     bool
	Exported   bool
	// Span is the range of its tokens in the file's Tokens, from the one after its name (the
	// signature) to the closing brace, excluded; empty when the file has no tokens.
	Span [2]int32
}

// Module is a Go module in the tree: the directory of a go.mod file and the module path it declares.
type Module struct {
	Dir  string // slash-separated, "." for the root
	Path string
	// Requires are the module paths the go.mod requires or replaces.
	Requires []string
	// Go is the version of its go directive, such as "go1.22", or "".
	Go string
}

// Coverage is a coverage report found for the scan, unparsed.
type Coverage struct {
	// Name is how the report is named in the output: a path relative to the root when the report is
	// inside the repository, only its base name otherwise, so no absolute path reaches the report.
	Name    string
	Tracked bool // the report is a file in the scanned commit
	Data    []byte
}

// Change is one path a commit touched, as git log --name-status reports it.
type Change struct {
	Status byte   // 'A' added, 'M' modified, 'R' renamed, 'D' deleted, 'C' copied, 'T' type changed
	Old    string // the path before a rename or copy
	Path   string
}

// Commit is one non-merge commit reachable from HEAD. Name and Email are the author's, with the
// commit's .mailmap applied.
type Commit struct {
	Hash        string
	Name, Email string
	Time        int64 // author time, Unix seconds
	NoTime      bool  // git printed no usable author time: the object is corrupt or crafted
	Changes     []Change
}

// History is the commit history reachable from HEAD.
type History struct {
	Commits  []Commit // newest first
	Shallow  bool     // the clone is shallow: older commits are missing
	TooLarge bool     // git log printed more than execx.MaxOutput or gitx.MaxChanges; Commits is empty
	Failed   bool     // git log failed; Commits is empty
}

// Repo is everything known about the scanned commit.
type Repo struct {
	Files []File
	// Paths holds every path in the commit's tree, including those that were not read.
	Paths    map[string]bool
	Modules  []Module
	Coverage *Coverage // nil when no report was found
	History  *History  // nil when the history was not read
}
