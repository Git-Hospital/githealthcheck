// Package facts is the model the analyzers read. Each file is read and parsed once, during the walk;
// analyzers never open files themselves.
package facts

// File is one source file in a recognised language, as it is in the work tree.
type File struct {
	Path      string // slash-separated, relative to the root
	Language  string
	Size      int64
	Lines     int
	Vendored  bool // under a vendored dependency directory
	Modified  bool // the work tree's content differs from the commit's blob
	Generated bool // marked as generated by its own header
	Test      bool // a test file by its language's convention
	// Package is the unit the file belongs to, a directory for Go. It is empty when the language's
	// own tooling ignores the file, as the go command ignores testdata and directories that start
	// with _ or .
	Package   string
	Functions int // function and method declarations with a body
}

// Module is a Go module in the tree: the directory of a go.mod file and the module path it declares.
type Module struct {
	Dir  string // slash-separated, "." for the root
	Path string
}

// Coverage is a coverage report found for the scan, unparsed.
type Coverage struct {
	// Name is how the report is named in the output: a path relative to the root when the report is
	// inside the repository, only its base name otherwise, so no absolute path reaches the report.
	Name    string
	Tracked bool // the report is a file in the scanned commit
	Data    []byte
}

// Change is one path a commit touched, as git log --name-status reports it.
type Change struct {
	Status byte   // 'A' added, 'M' modified, 'R' renamed, 'D' deleted, 'C' copied, 'T' type changed
	Old    string // the path before a rename or copy
	Path   string
}

// Commit is one non-merge commit reachable from HEAD. Name and Email are the author's, with the
// commit's .mailmap applied.
type Commit struct {
	Hash        string
	Name, Email string
	Time        int64 // author time, Unix seconds
	NoTime      bool  // git printed no usable author time: the object is corrupt or crafted
	Changes     []Change
}

// History is the commit history reachable from HEAD.
type History struct {
	Commits  []Commit // newest first
	Shallow  bool     // the clone is shallow: older commits are missing
	TooLarge bool     // git log printed more than execx.MaxOutput; Commits is empty
}

// Repo is everything known about the scanned commit.
type Repo struct {
	Files []File
	// Paths holds every path in the commit's tree, including those that were not read.
	Paths    map[string]bool
	Modules  []Module
	Coverage *Coverage // nil when no report was found
	History  *History  // nil when the history was not read
}
